#!/usr/bin/env python3
"""Cost guardrails for an AWS account: budgets, anomaly detection, cost allocation tags.

This is the cost-side counterpart to the GuardDuty alerting path in this repository.
The security path answers "is something attacking this account". This one answers
"is something costing money that should not be", which is the same question asked of
the bill instead of the threat feed, and it reuses the same delivery mechanism: one
SNS topic, one subscription, email at the end of it.

Three controls are created, and they are not interchangeable:

  1. AWS Budgets           - a ceiling you set. Fires when spend crosses a threshold
                             you chose in advance. Catches the slow leak you forgot
                             about, and it is the only one of the three that can fire
                             on a FORECAST rather than on money already spent.
  2. Cost Anomaly Detection- a model AWS trains on your own spend history. Fires when
                             today does not look like your normal, whatever your normal
                             is. Catches the thing you did not think to set a ceiling
                             on, which is the failure mode Budgets has by design.
  3. Cost allocation tags  - not an alarm at all. Activating a tag key is what makes
                             the other two able to say *which* project or environment
                             the money went to. Without it an anomaly tells you the
                             bill moved and nothing about where.

A note on wiring, because it is easy to assume otherwise: Budgets and Cost Anomaly
Detection each publish to SNS *directly*. Neither is routed through EventBridge. The
GuardDuty path in this repository does use EventBridge, because GuardDuty emits
findings onto the event bus and the rule is what filters them by severity. Cost alerts
have no equivalent bus event, so there is nothing for a rule to match on. The topic
policy therefore has to name `budgets.amazonaws.com` and `costalerts.amazonaws.com` as
publishers rather than `events.amazonaws.com`.

Both AWS Budgets and Cost Explorer are global services with a single endpoint in
us-east-1. Calling them in any other region fails, which is why the region is pinned
below rather than taken from the environment.

Usage
-----
    python finops_alerts.py plan   --email you@example.com --monthly-limit 20
    python finops_alerts.py deploy --email you@example.com --monthly-limit 20
    python finops_alerts.py status
    python finops_alerts.py teardown --yes

`plan` makes no API calls that change anything and prints every request it would send.
`deploy` is idempotent: run it twice and the second run reports "exists" rather than
failing or creating duplicates.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from typing import Any

import boto3
from botocore.exceptions import BotoCoreError, ClientError, NoCredentialsError

# Budgets and Cost Explorer are global, with one endpoint, in us-east-1.
GLOBAL_REGION = "us-east-1"

DEFAULTS = {
    "topic_name": "aws-cost-alerts",
    "budget_name": "monthly-account-cost",
    "monitor_name": "service-spend-monitor",
    "subscription_name": "immediate-anomaly-alerts",
    # Percentages of the monthly limit at which to fire.
    "actual_thresholds": [50.0, 80.0, 100.0],
    # A forecast breach is worth knowing about before the money is gone.
    "forecast_thresholds": [100.0],
    # Absolute dollar impact at or above which an anomaly is worth an email.
    # Below a few dollars the model is noisy on a small account.
    "anomaly_threshold_usd": 5.0,
    "cost_tag_keys": ["Project", "Environment"],
}


class Planned(Exception):
    """Raised internally to abort a mutating call during `plan`."""


@dataclass
class Runner:
    """Wraps the AWS clients so `plan` and `deploy` share one code path.

    Every mutating call goes through `self.call`, which in plan mode records the
    request and returns a stub instead of sending it. That way the planned output is
    generated by the same code that does the work, rather than by a second description
    of it that can drift.
    """

    dry_run: bool = False
    region: str = GLOBAL_REGION
    session: Any = None
    planned: list[dict] = field(default_factory=list)
    _clients: dict = field(default_factory=dict)

    def client(self, name: str):
        if name not in self._clients:
            sess = self.session or boto3.Session()
            self._clients[name] = sess.client(name, region_name=self.region)
        return self._clients[name]

    def account_id(self) -> str:
        if self.dry_run:
            try:
                return self.client("sts").get_caller_identity()["Account"]
            except (ClientError, BotoCoreError):
                # Planning has to work on a machine with no credentials at all, so an
                # unknown account id is a placeholder rather than an error.
                return "<account-id>"
        return self.client("sts").get_caller_identity()["Account"]

    def call(self, service: str, op: str, **kwargs):
        """Send a mutating request, or record it when planning."""
        if self.dry_run:
            self.planned.append({"service": service, "operation": op, "request": kwargs})
            return {}
        return getattr(self.client(service), op)(**kwargs)

    def read(self, service: str, op: str, **kwargs):
        """Send a read-only request. Safe in plan mode, so it is not recorded."""
        return getattr(self.client(service), op)(**kwargs)


# --------------------------------------------------------------------------- SNS

def topic_policy(topic_arn: str, account_id: str) -> dict:
    """Allow exactly the two cost services to publish, and only for this account.

    The `aws:SourceAccount` condition is the part that matters. Without it the
    statement allows *any* account's budget or anomaly subscription to publish to this
    topic, because the principal is an AWS service rather than a specific caller - the
    confused-deputy shape. With it, a publish is only accepted when the service is
    acting on behalf of this account.
    """
    return {
        "Version": "2012-10-17",
        "Id": "cost-alerts-publish-policy",
        "Statement": [
            {
                "Sid": "AllowCostServicesToPublish",
                "Effect": "Allow",
                "Principal": {
                    "Service": ["budgets.amazonaws.com", "costalerts.amazonaws.com"]
                },
                "Action": "sns:Publish",
                "Resource": topic_arn,
                "Condition": {"StringEquals": {"aws:SourceAccount": account_id}},
            }
        ],
    }


def ensure_topic(r: Runner, name: str, email: str, account_id: str) -> str:
    """Create the topic, attach the publish policy, subscribe the address.

    `create_topic` is idempotent in SNS: calling it for a name that already exists
    returns the existing ARN rather than erroring, so this needs no exists-check.
    """
    if r.dry_run:
        arn = f"arn:aws:sns:{r.region}:{account_id}:{name}"
        r.call("sns", "create_topic", Name=name)
    else:
        arn = r.call("sns", "create_topic", Name=name)["TopicArn"]

    r.call(
        "sns",
        "set_topic_attributes",
        TopicArn=arn,
        AttributeName="Policy",
        AttributeValue=json.dumps(topic_policy(arn, account_id)),
    )

    # Subscribing the same endpoint twice is a no-op in SNS, but checking first keeps
    # the deploy output honest about what actually changed.
    already = False
    if not r.dry_run:
        try:
            for page in r.client("sns").get_paginator("list_subscriptions_by_topic").paginate(
                TopicArn=arn
            ):
                if any(s.get("Endpoint") == email for s in page.get("Subscriptions", [])):
                    already = True
                    break
        except ClientError:
            pass

    if already:
        print(f"  subscription   exists   {email}")
    else:
        r.call("sns", "subscribe", TopicArn=arn, Protocol="email", Endpoint=email)
        print(f"  subscription   created  {email}  (confirm the email AWS sends)")

    return arn


# ----------------------------------------------------------------------- Budgets

def build_budget(name: str, limit: float) -> dict:
    """A monthly cost budget for the whole account.

    `IncludeCredit` and `IncludeRefund` are off deliberately. Leaving them on lets a
    credit mask real spend: the bill looks flat while usage climbs, and the alarm that
    should have fired does not. For a guardrail you want to see the usage, not the net.
    """
    return {
        "BudgetName": name,
        "BudgetLimit": {"Amount": f"{limit:g}", "Unit": "USD"},
        "TimeUnit": "MONTHLY",
        "BudgetType": "COST",
        "CostTypes": {
            "IncludeTax": True,
            "IncludeSubscription": True,
            "UseBlended": False,
            "IncludeRefund": False,
            "IncludeCredit": False,
            "IncludeUpfront": True,
            "IncludeRecurring": True,
            "IncludeOtherSubscription": True,
            "IncludeSupport": True,
            "IncludeDiscount": True,
            "UseAmortized": False,
        },
    }


def build_notifications(topic_arn: str, actual: list[float],
                        forecast: list[float]) -> list[dict]:
    subs = [{"SubscriptionType": "SNS", "Address": topic_arn}]

    def notify(kind: str, threshold: float) -> dict:
        return {
            "Notification": {
                "NotificationType": kind,
                "ComparisonOperator": "GREATER_THAN",
                "Threshold": threshold,
                "ThresholdType": "PERCENTAGE",
            },
            "Subscribers": subs,
        }

    return ([notify("ACTUAL", t) for t in actual]
            + [notify("FORECASTED", t) for t in forecast])


def ensure_budget(r: Runner, account_id: str, name: str, limit: float,
                  topic_arn: str, actual: list[float], forecast: list[float]) -> None:
    budget = build_budget(name, limit)
    notifications = build_notifications(topic_arn, actual, forecast)

    exists = False
    if not r.dry_run:
        try:
            r.read("budgets", "describe_budget", AccountId=account_id, BudgetName=name)
            exists = True
        except ClientError as e:
            if e.response["Error"]["Code"] != "NotFoundException":
                raise

    if exists:
        # update_budget does not carry notifications, so the limit and the thresholds
        # are updated through two different calls. Easy thing to get wrong.
        r.call("budgets", "update_budget", AccountId=account_id, NewBudget=budget)
        print(f"  budget         updated  {name}  ${limit:g}/month")
    else:
        r.call("budgets", "create_budget", AccountId=account_id, Budget=budget,
               NotificationsWithSubscribers=notifications)
        print(f"  budget         created  {name}  ${limit:g}/month "
              f"({len(notifications)} thresholds)")


# ------------------------------------------------------ Cost Anomaly Detection

def ensure_anomaly_monitor(r: Runner, name: str) -> str:
    """A monitor segments spend so the model knows what to compare against.

    DIMENSIONAL on SERVICE is the right default for a single account: it learns a
    separate baseline per service, so $40 of unexpected SageMaker reads as an anomaly
    even in a month where total spend happens to look normal. A single whole-account
    baseline would hide exactly that.
    """
    monitor = {
        "MonitorName": name,
        "MonitorType": "DIMENSIONAL",
        "MonitorDimension": "SERVICE",
    }
    if not r.dry_run:
        for page in r.client("ce").get_paginator("get_anomaly_monitors").paginate():
            for m in page.get("AnomalyMonitors", []):
                if m["MonitorName"] == name:
                    print(f"  monitor        exists   {name}")
                    return m["MonitorArn"]
        arn = r.call("ce", "create_anomaly_monitor", AnomalyMonitor=monitor)["MonitorArn"]
        print(f"  monitor        created  {name}  (DIMENSIONAL on SERVICE)")
        return arn

    r.call("ce", "create_anomaly_monitor", AnomalyMonitor=monitor)
    print(f"  monitor        created  {name}  (DIMENSIONAL on SERVICE)")
    return "<monitor-arn>"


def build_threshold_expression(usd: float) -> dict:
    """Fire at or above an absolute dollar impact.

    ANOMALY_TOTAL_IMPACT_ABSOLUTE rather than _PERCENTAGE on purpose. On a small
    account a percentage threshold is useless: going from $0.40 to $4 is a 900% jump
    and not worth an email, while on a large account 10% can be thousands of dollars
    and very much is. Dollars mean the same thing at every account size.
    """
    return {
        "Dimensions": {
            "Key": "ANOMALY_TOTAL_IMPACT_ABSOLUTE",
            "MatchOptions": ["GREATER_THAN_OR_EQUAL"],
            "Values": [str(usd)],
        }
    }


def ensure_anomaly_subscription(r: Runner, name: str, monitor_arn: str,
                                topic_arn: str, usd: float) -> str:
    """Frequency IMMEDIATE is what makes this an alert rather than a digest.

    IMMEDIATE is also the only frequency that accepts an SNS subscriber; DAILY and
    WEEKLY are email-only. So choosing SNS and choosing immediacy are the same choice,
    not two.
    """
    sub = {
        "SubscriptionName": name,
        "MonitorArnList": [monitor_arn],
        "Subscribers": [{"Type": "SNS", "Address": topic_arn}],
        "Frequency": "IMMEDIATE",
        "ThresholdExpression": build_threshold_expression(usd),
    }
    if not r.dry_run:
        for page in r.client("ce").get_paginator("get_anomaly_subscriptions").paginate():
            for s in page.get("AnomalySubscriptions", []):
                if s["SubscriptionName"] == name:
                    print(f"  subscription   exists   {name}")
                    return s["SubscriptionArn"]
        arn = r.call("ce", "create_anomaly_subscription",
                     AnomalySubscription=sub)["SubscriptionArn"]
        print(f"  anomaly alert  created  {name}  (immediate, >= ${usd:g})")
        return arn

    r.call("ce", "create_anomaly_subscription", AnomalySubscription=sub)
    print(f"  anomaly alert  created  {name}  (immediate, >= ${usd:g})")
    return "<subscription-arn>"


# ------------------------------------------------------- Cost allocation tags

def activate_cost_tags(r: Runner, keys: list[str]) -> None:
    """Activating a tag key is retroactive in reporting but not in tagging.

    Once active, Cost Explorer can group by that key - but only for usage recorded
    after the resources themselves were tagged. Activating it late does not
    reconstruct the attribution of spend that was already incurred untagged, which is
    the reason to do this on day one rather than when the bill first surprises you.
    """
    if not keys:
        return
    payload = [{"TagKey": k, "Status": "Active"} for k in keys]
    res = r.call("ce", "update_cost_allocation_tags_status",
                 CostAllocationTagsStatus=payload)
    errors = (res or {}).get("Errors", []) if not r.dry_run else []
    if errors:
        # A key that has never appeared on a resource cannot be activated. That is a
        # real answer, not a failure: it means nothing is tagged with it yet.
        for e in errors:
            print(f"  cost tag       skipped  {e.get('TagKey')}: {e.get('Message')}")
    active = [k for k in keys if k not in {e.get("TagKey") for e in errors}]
    if active:
        print(f"  cost tags      active   {', '.join(active)}")


# ------------------------------------------------------------------- commands

def cmd_deploy(args, session=None) -> int:
    r = Runner(dry_run=args.command == "plan", session=session)
    try:
        account_id = r.account_id()
    except (NoCredentialsError, ClientError) as e:
        print(f"No usable AWS credentials: {e}", file=sys.stderr)
        return 2

    verb = "Planning" if r.dry_run else "Deploying"
    print(f"{verb} cost guardrails in account {account_id} ({r.region})")

    topic_arn = ensure_topic(r, args.topic_name, args.email, account_id)
    ensure_budget(r, account_id, args.budget_name, args.monthly_limit, topic_arn,
                  args.actual_thresholds, args.forecast_thresholds)
    monitor_arn = ensure_anomaly_monitor(r, args.monitor_name)
    ensure_anomaly_subscription(r, args.subscription_name, monitor_arn, topic_arn,
                                args.anomaly_threshold_usd)
    activate_cost_tags(r, args.cost_tag_keys)

    if r.dry_run:
        print(f"\n{len(r.planned)} request(s) would be sent:\n")
        print(json.dumps(r.planned, indent=2, default=str))
        print("\nNothing was changed. Re-run with `deploy` to apply.")
    else:
        print("\nDone. Confirm the SNS subscription email before trusting the alerts -")
        print("an unconfirmed subscription silently drops every message.")
    return 0


def cmd_status(args, session=None) -> int:
    r = Runner(session=session)
    try:
        account_id = r.account_id()
    except (NoCredentialsError, ClientError) as e:
        print(f"No usable AWS credentials: {e}", file=sys.stderr)
        return 2

    print(f"Account {account_id} ({r.region})\n")

    try:
        b = r.read("budgets", "describe_budget", AccountId=account_id,
                   BudgetName=args.budget_name)["Budget"]
        spent = b.get("CalculatedSpend", {}).get("ActualSpend", {}).get("Amount", "?")
        limit = b["BudgetLimit"]["Amount"]
        print(f"budget        {b['BudgetName']}: {spent} / {limit} USD this month")
    except ClientError as e:
        print(f"budget        none ({e.response['Error']['Code']})")

    try:
        mons = r.read("ce", "get_anomaly_monitors").get("AnomalyMonitors", [])
        print(f"monitors      {len(mons)}: "
              + (", ".join(m["MonitorName"] for m in mons) or "none"))
        subs = r.read("ce", "get_anomaly_subscriptions").get("AnomalySubscriptions", [])
        for s in subs:
            dests = ", ".join(x["Address"] for x in s.get("Subscribers", []))
            print(f"anomaly alert {s['SubscriptionName']}: {s['Frequency']} -> {dests}")
        if not subs:
            print("anomaly alert none")
    except ClientError as e:
        print(f"anomaly       unavailable ({e.response['Error']['Code']})")

    return 0


def cmd_teardown(args, session=None) -> int:
    if not args.yes:
        print("Refusing to delete without --yes.", file=sys.stderr)
        return 2
    r = Runner(session=session)
    account_id = r.account_id()

    # Subscriptions reference monitors, so they go first.
    for page in r.client("ce").get_paginator("get_anomaly_subscriptions").paginate():
        for s in page.get("AnomalySubscriptions", []):
            if s["SubscriptionName"] == args.subscription_name:
                r.call("ce", "delete_anomaly_subscription",
                       SubscriptionArn=s["SubscriptionArn"])
                print(f"  deleted subscription {s['SubscriptionName']}")
    for page in r.client("ce").get_paginator("get_anomaly_monitors").paginate():
        for m in page.get("AnomalyMonitors", []):
            if m["MonitorName"] == args.monitor_name:
                r.call("ce", "delete_anomaly_monitor", MonitorArn=m["MonitorArn"])
                print(f"  deleted monitor {m['MonitorName']}")
    try:
        r.call("budgets", "delete_budget", AccountId=account_id,
               BudgetName=args.budget_name)
        print(f"  deleted budget {args.budget_name}")
    except ClientError as e:
        if e.response["Error"]["Code"] != "NotFoundException":
            raise

    # The topic is left in place on purpose: the GuardDuty path in this repository may
    # be publishing to it, and deleting it would take that down too.
    print("  left the SNS topic alone (the GuardDuty path may share it)")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="finops_alerts",
        description="Budgets, cost anomaly detection and cost allocation tags for one "
                    "AWS account, delivered over SNS.")
    p.add_argument("command", choices=["plan", "deploy", "status", "teardown"])
    p.add_argument("--email", help="address to subscribe to the SNS topic")
    p.add_argument("--monthly-limit", type=float, default=20.0,
                   help="monthly budget ceiling in USD (default: 20)")
    p.add_argument("--anomaly-threshold-usd", type=float,
                   default=DEFAULTS["anomaly_threshold_usd"],
                   help="minimum absolute dollar impact worth an alert (default: 5)")
    p.add_argument("--topic-name", default=DEFAULTS["topic_name"])
    p.add_argument("--budget-name", default=DEFAULTS["budget_name"])
    p.add_argument("--monitor-name", default=DEFAULTS["monitor_name"])
    p.add_argument("--subscription-name", default=DEFAULTS["subscription_name"])
    p.add_argument("--cost-tag-keys", nargs="*", default=DEFAULTS["cost_tag_keys"],
                   help="tag keys to activate for cost allocation")
    p.add_argument("--actual-thresholds", nargs="*", type=float,
                   default=DEFAULTS["actual_thresholds"])
    p.add_argument("--forecast-thresholds", nargs="*", type=float,
                   default=DEFAULTS["forecast_thresholds"])
    p.add_argument("--yes", action="store_true", help="required by teardown")
    return p


def main(argv: list[str] | None = None, session=None) -> int:
    args = build_parser().parse_args(argv)
    if args.command in ("plan", "deploy") and not args.email:
        print("--email is required for plan and deploy.", file=sys.stderr)
        return 2
    if args.command in ("plan", "deploy"):
        return cmd_deploy(args, session=session)
    if args.command == "status":
        return cmd_status(args, session=session)
    return cmd_teardown(args, session=session)


if __name__ == "__main__":
    sys.exit(main())
